import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { runInNewContext } from "node:vm";
import ts from "typescript";

const source = await readFile("src/lib/ecosystem.ts", "utf8");
const helpers = {};
runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: helpers, URL });
const { DEFAULT_ECOSYSTEM, parseEcosystem, visibleEcosystem, parseAssociatesGallery } = helpers;
assert.equal(visibleEcosystem(DEFAULT_ECOSYSTEM).length, 5);
assert.equal(parseEcosystem(null).length, 5);
assert.equal(parseEcosystem("[]").length, 0);
assert.equal(parseEcosystem("broken").length, 0);
assert.equal(visibleEcosystem([{ ...DEFAULT_ECOSYSTEM[1], url: "javascript:alert(1)" }]).length, 0);
assert.equal(parseAssociatesGallery(JSON.stringify({ images: ["javascript:bad", "//evil.com", "https://example.com/logo.png"], showIndividual: false })).images.length, 1);
assert.equal(parseAssociatesGallery(null).showIndividual, false);
const rows = [{ ...DEFAULT_ECOSYSTEM[1], name: "Nombre editado", url: "https://example.com" }];
assert.equal(visibleEcosystem(parseEcosystem(JSON.stringify(rows)))[0].name, "Nombre editado");
let authorized = false;
let stored = null;
const invalidated = [];
const actions = {};
runInNewContext(ts.transpileModule(await readFile("src/lib/actions/ecosystem.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: actions, require: (name) => {
  if (name === "next/cache") return { revalidatePath: (...args) => invalidated.push(args) };
  if (name === "@/lib/auth") return { getCurrentAdmin: async () => authorized };
  if (name === "@/lib/ecosystem") return helpers;
  if (name === "@/lib/supabase/server") return { createServiceSupabase: () => ({ from: () => ({ upsert: async (value) => { stored = value; return { error: null }; } }) }) };
  throw new Error(name);
} });
assert.equal((await actions.saveEcosystem(rows)).ok, false);
assert.equal((await actions.saveAssociatesGallery({ images: [], showIndividual: false })).ok, false);
assert.equal(stored, null);
authorized = true;
assert.equal((await actions.saveEcosystem(DEFAULT_ECOSYSTEM)).ok, true);
assert.equal(JSON.parse(stored.value)[0].url, "");
assert.equal((await actions.saveEcosystem([{ ...rows[0], url: "javascript:bad" }])).ok, false);
assert.equal((await actions.saveEcosystem(rows)).ok, true);
assert.equal(stored.key, "ecosystem_items");
assert.equal(JSON.parse(stored.value)[0].name, "Nombre editado");
assert.ok(invalidated.some(([path, type]) => path === "/" && type === "layout"));
assert.equal((await actions.saveEcosystem([])).ok, true);
assert.equal(stored.value, "[]");
assert.equal((await actions.saveAssociatesGallery({ images: ["https://example.com/logo.png"], showIndividual: true })).ok, true);
assert.equal(stored.key, "associates_gallery");
assert.ok(invalidated.some(([path]) => path === "/nosotros/asociados-y-aliados"));
console.log("PASS: lista compartida, borradores, edición, eliminación, URLs, permisos, galería independiente y caché.");
